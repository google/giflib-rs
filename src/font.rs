/// Draw an 8×8 font string onto the image raster.
pub(crate) fn gif_draw_text8x8(
    image: &mut SavedImage,
    x: c_int,
    y: c_int,
    legend: &[u8],
    color: c_int,
) {
    if x < 0 || y < 0 {
        return;
    }

    let width = image.ImageDesc.Width as usize;
    let raster = image.raster_bits_mut();

    for row in 0..GIF_FONT_HEIGHT {
        let Some(base_offset) =
            width.checked_mul(y as usize + row).and_then(|v| v.checked_add(x as usize))
        else {
            return;
        };
        let mut col = 0usize;
        for &ch_byte in legend {
            let ch = (ch_byte & 0x7f) as usize;
            for j in 0..GIF_FONT_WIDTH {
                if ((GIF_ASCII_TABLE_8X8[ch][row] as u16) & (1u16 << (GIF_FONT_WIDTH - j))) != 0 {
                    if let Some(idx) = base_offset.checked_add(col) {
                        if idx < raster.len() {
                            raster[idx] = color as GifByteType;
                        }
                    }
                }
                col += 1;
            }
        }
    }
}

/// Draw the outline of a rectangle.
pub(crate) fn gif_draw_box(
    image: &mut SavedImage,
    x: c_int,
    y: c_int,
    w: c_int,
    d: c_int,
    color: c_int,
) {
    if x < 0 || y < 0 || w <= 0 || d <= 0 {
        return;
    }
    let width = image.ImageDesc.Width as usize;
    let raster = image.raster_bits_mut();
    let Some(base) = width.checked_mul(y as usize).and_then(|v| v.checked_add(x as usize)) else {
        return;
    };

    // Top and bottom edges
    for j in 0..w as usize {
        if let Some(top) = base.checked_add(j) {
            if top < raster.len() {
                raster[top] = color as GifByteType;
            }
        }
        if let Some(bottom) = (d as usize)
            .checked_mul(width)
            .and_then(|v| base.checked_add(v))
            .and_then(|v| v.checked_add(j))
        {
            if bottom < raster.len() {
                raster[bottom] = color as GifByteType;
            }
        }
    }
    // Left and right edges
    for j in 0..d as usize {
        if let Some(left) = j.checked_mul(width).and_then(|v| base.checked_add(v)) {
            if left < raster.len() {
                raster[left] = color as GifByteType;
            }
        }
        if let Some(right) = j
            .checked_mul(width)
            .and_then(|v| base.checked_add(v))
            .and_then(|v| v.checked_add(w as usize))
        {
            if right < raster.len() {
                raster[right] = color as GifByteType;
            }
        }
    }
}

/// Fill a rectangle.
pub(crate) fn gif_draw_rectangle(
    image: &mut SavedImage,
    x: c_int,
    y: c_int,
    w: c_int,
    d: c_int,
    color: c_int,
) {
    if x < 0 || y < 0 || w <= 0 || d <= 0 {
        return;
    }
    let width = image.ImageDesc.Width as usize;
    let raster = image.raster_bits_mut();
    let Some(bp) = width.checked_mul(y as usize).and_then(|v| v.checked_add(x as usize)) else {
        return;
    };

    for i in 0..d as usize {
        let Some(start) = i.checked_mul(width).and_then(|v| bp.checked_add(v)) else {
            return;
        };
        let Some(end) = start.checked_add(w as usize) else {
            return;
        };
        if end <= raster.len() {
            raster[start..end].fill(color as u8);
        }
    }
}

/// Draw text in a box.
pub(crate) fn gif_draw_boxed_text8x8(
    image: &mut SavedImage,
    x: c_int,
    y: c_int,
    legend: &[u8],
    border: c_int,
    bg: c_int,
    fg: c_int,
) {
    // Compute text dimensions.
    let mut j = 0i32;
    let mut line_count = 0i32;
    let mut text_width = 0i32;
    for &ch in legend {
        if ch == b'\r' {
            if j > text_width {
                text_width = j;
            }
            j = 0;
            line_count += 1;
        } else if ch != b'\t' {
            j += 1;
        }
    }
    line_count += 1;
    if j > text_width {
        text_width = j;
    }

    // Fill the box
    gif_draw_rectangle(
        image,
        x + 1,
        y + 1,
        border + text_width * GIF_FONT_WIDTH as c_int + border - 1,
        border + line_count * GIF_FONT_HEIGHT as c_int + border - 1,
        bg,
    );

    // Split on \r and draw each line
    let mut line_idx = 0i32;
    for line in legend.split(|&b| b == b'\r') {
        let (text, leadspace) = if line.first() == Some(&b'\t') {
            let trimmed = &line[1..];
            let lead = (text_width - trimmed.len() as i32) / 2;
            (trimmed, lead)
        } else {
            (line, 0)
        };

        gif_draw_text8x8(
            image,
            x + border + leadspace * GIF_FONT_WIDTH as c_int,
            y + border + GIF_FONT_HEIGHT as c_int * line_idx,
            text,
            fg,
        );
        line_idx += 1;
    }

    // Draw the outline box
    gif_draw_box(
        image,
        x,
        y,
        border + text_width * GIF_FONT_WIDTH as c_int + border,
        border + line_count * GIF_FONT_HEIGHT as c_int + border,
        fg,
    );
}
